declare const process: { memoryUsage(): { heapUsed: number } };
import * as THREE from 'three';
import { HeightField } from '../src/world/heightmap';
import { RoadGraph } from '../src/sim/roadGraph';
import { WorldGen } from '../src/world/worldgen';
import { RoadBuilder } from '../src/world/roadMesh';
import { TerrainLOD } from '../src/world/terrainMesh';
import { buildBuildings } from '../src/world/buildingMesh';
const hf = new HeightField(); hf.bake();
const g = new RoadGraph(hf);
const wd = new WorldGen(hf, g).generate();
let t = Date.now();
const tl = new TerrainLOD(hf, new THREE.MeshBasicMaterial(), 64); tl.update(new THREE.Vector3(-1400,0,700), true);
console.log('terrain ms', Date.now()-t, 'mem', Math.round(process.memoryUsage().heapUsed/1e6));
t = Date.now();
const grp = new THREE.Group();
const m = new THREE.MeshBasicMaterial();
new RoadBuilder(hf, g, wd).build({asphalt:m as any, marking:m as any, pavers:m as any, grass:m as any, concrete:m as any, curb:m as any, deck:m as any}, grp);
let verts = 0; grp.traverse(o => { const mm = o as THREE.Mesh; if (mm.geometry) verts += mm.geometry.getAttribute('position').count; });
console.log('roads ms', Date.now()-t, 'meshes', grp.children.length, 'verts', verts, 'mem', Math.round(process.memoryUsage().heapUsed/1e6));
t = Date.now();
const bm = buildBuildings(wd.buildings, m, m);
verts = 0; bm.group.traverse(o => { const mm = o as THREE.Mesh; if (mm.geometry) verts += mm.geometry.getAttribute('position').count; });
console.log('buildings ms', Date.now()-t, 'meshes', bm.group.children.length, 'verts', verts);
